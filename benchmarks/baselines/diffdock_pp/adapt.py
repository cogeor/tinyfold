"""Adapt our parquet samples to DiffDock-PP's DB5Loader input format.

DiffDock-PP's DB5Loader expects, per complex:
    {root}/structures/{name}_r_b.pdb    -- receptor (bound)
    {root}/structures/{name}_l_b.pdb    -- ligand (bound)
    {root}/splits_test.csv              -- 'path,split' rows, path = name

We have parquet rows with:
    atom_coords  flat [n_atoms*3] real Angstroms (N,CA,C,O per residue)
    seq          [n_res] aa indices 0-19
    chain_id_res [n_res] {0, 1} -- chain 0 = receptor, chain 1 = ligand
    sample_id    str like '1ebo.pdb2_1'

This script picks samples from a clean split JSON and writes one PDB pair
plus a splits_test.csv into the chosen output directory.

NOTE: DPP's dips_esm_inference.yaml uses ``resolution: residue`` which only
needs CA atoms. We write full backbone (N,CA,C,O) anyway — it's a superset.
"""

from __future__ import annotations

import argparse
import csv
import json
import sys
from pathlib import Path

import numpy as np
import pyarrow.parquet as pq


AA_3LETTER = [
    "ALA", "ARG", "ASN", "ASP", "CYS", "GLN", "GLU", "GLY", "HIS", "ILE",
    "LEU", "LYS", "MET", "PHE", "PRO", "SER", "THR", "TRP", "TYR", "VAL",
]
BACKBONE = ["N", "CA", "C", "O"]


def _pdb_line(serial: int, atom_name: str, res_name: str, chain: str,
              res_seq: int, x: float, y: float, z: float, element: str) -> str:
    """Render a single ATOM record. Strict PDB columnar format."""
    # ATOM/HETATM, serial, atom_name, altLoc, resName, chainID, resSeq, iCode,
    # x, y, z, occupancy, tempFactor, element, charge.
    # Cols (1-based): 1-6 record, 7-11 serial, 13-16 name, 17 altLoc, 18-20 resName,
    #                 22 chain, 23-26 resSeq, 27 iCode, 31-38 x, 39-46 y, 47-54 z,
    #                 55-60 occ, 61-66 temp, 77-78 element.
    name = atom_name if len(atom_name) == 4 else f" {atom_name:<3s}"
    return (
        f"ATOM  {serial:5d} {name} {res_name:3s} {chain}{res_seq:4d}    "
        f"{x:8.3f}{y:8.3f}{z:8.3f}  1.00  0.00          {element:>2s}\n"
    )


def write_pdb(
    path: Path,
    atoms: np.ndarray,   # [n_res, 4, 3]
    aa_idx: np.ndarray,  # [n_res] in 0-19
    chain: str,
) -> None:
    """Write a single-chain backbone PDB."""
    n_res = atoms.shape[0]
    serial = 1
    lines = [
        "HEADER    BENCHMARK ADAPTER OUTPUT\n",
        "REMARK   1 backbone N,CA,C,O only - generated by benchmarks/baselines/diffdock_pp/adapt.py\n",
    ]
    for r in range(n_res):
        res_name = AA_3LETTER[int(aa_idx[r])]
        for a, atom_name in enumerate(BACKBONE):
            x, y, z = atoms[r, a]
            elem = atom_name[0]  # N/C/C/O — element is the first letter for backbone
            lines.append(
                _pdb_line(serial, atom_name, res_name, chain, r + 1,
                          float(x), float(y), float(z), elem)
            )
            serial += 1
    lines.append("TER\n")
    lines.append("END\n")
    path.write_text("".join(lines))


def adapt_one(table, idx: int, sample_id: str, structures_dir: Path) -> tuple[Path, Path]:
    """Write the receptor/ligand PDB pair for one sample."""
    coords_flat = np.asarray(table["atom_coords"][idx].as_py(), dtype=np.float32)
    n_atoms = coords_flat.shape[0] // 3
    n_res = n_atoms // 4
    atoms = coords_flat.reshape(n_res, 4, 3)
    aa = np.asarray(table["seq"][idx].as_py(), dtype=np.int64)
    chains = np.asarray(table["chain_id_res"][idx].as_py(), dtype=np.int64)

    chain_a = chains == 0
    chain_b = chains == 1
    assert chain_a.sum() > 0 and chain_b.sum() > 0, f"{sample_id}: missing a chain"

    # Receptor = chain A, ligand = chain B. (Arbitrary but consistent.)
    rec_path = structures_dir / f"{sample_id}_r_b.pdb"
    lig_path = structures_dir / f"{sample_id}_l_b.pdb"
    write_pdb(rec_path, atoms[chain_a], aa[chain_a], chain="A")
    write_pdb(lig_path, atoms[chain_b], aa[chain_b], chain="B")
    return rec_path, lig_path


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--split", required=True, type=Path,
                   help="Path to a benchmarks/splits/*.json file.")
    p.add_argument("--out", required=True, type=Path,
                   help="Output dataset directory (will create structures/ + splits_test.csv inside).")
    p.add_argument("--parquet", default="data/processed/samples.parquet")
    p.add_argument("--limit", type=int, default=0,
                   help="If >0, only convert the first N samples (debug).")
    args = p.parse_args()

    print(f"Reading {args.parquet}")
    table = pq.read_table(args.parquet)
    id_to_idx = {sid: i for i, sid in enumerate(table["sample_id"].to_pylist())}

    split = json.load(open(args.split))
    test_ids = split["test_ids"]
    if args.limit > 0:
        test_ids = test_ids[:args.limit]
    print(f"Split {args.split.name}: {len(test_ids)} samples")

    structures_dir = args.out / "structures"
    structures_dir.mkdir(parents=True, exist_ok=True)

    csv_rows: list[tuple[str, str]] = []
    n_written = 0
    for sid in test_ids:
        if sid not in id_to_idx:
            print(f"  [skip] {sid}: not in parquet")
            continue
        adapt_one(table, id_to_idx[sid], sid, structures_dir)
        csv_rows.append((sid, "test"))
        n_written += 1

    csv_path = args.out / "splits_test.csv"
    with open(csv_path, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["path", "split"])
        w.writerows(csv_rows)

    print(f"Wrote {n_written} PDB pairs to {structures_dir}")
    print(f"Wrote splits CSV: {csv_path}")
    print()
    print("Next: tell DiffDock-PP to read from this directory.")
    print(f"  edit config to set data_path: {args.out.resolve()}")
    print(f"  edit config to set data_file: {csv_path.resolve()}")


if __name__ == "__main__":
    main()
